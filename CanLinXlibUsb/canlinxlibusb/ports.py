"""
ports.py - which COM port belongs to the PwrSup function of a CanLinX board.

>>> CanLinX (not generated by CubeMX2) <<<

The board carries ONE virtual COM port, PwrSup (USB interface 0). CAN and LIN do
not use a COM port: they are on the WinUSB interface, see device.py.

Windows keeps the port name in the registry under the interface that owns it,
keyed by the board's USB serial; elsewhere the port's USB location ends in
``.<interface>``. When the port cannot be determined, None is returned and the
caller should fall back to whatever it was given.
"""

from __future__ import annotations

import sys
from typing import Optional

from .device import CANLINX_PID, CANLINX_VID

#: USB interface number of the PwrSup CDC ACM function.
INTERFACE_PWRSUP = 0


def _windows_port(vid: int, pid: int, serial: str, interface: int) -> Optional[str]:
    import winreg

    base = r"SYSTEM\CurrentControlSet\Enum\USB"
    try:
        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,
                            rf"{base}\VID_{vid:04X}&PID_{pid:04X}\{serial}") as key:
            prefix = winreg.QueryValueEx(key, "ParentIdPrefix")[0]
        path = (rf"{base}\VID_{vid:04X}&PID_{pid:04X}&MI_{interface:02X}"
                rf"\{prefix}&{interface:04X}\Device Parameters")
        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, path) as key:
            return winreg.QueryValueEx(key, "PortName")[0]
    except OSError:
        return None


def _location_port(vid: int, pid: int, serial: str, interface: int) -> Optional[str]:
    import serial.tools.list_ports as list_ports

    for p in list_ports.comports():
        if p.vid == vid and p.pid == pid and p.serial_number == serial:
            location = p.location or ""
            if location.endswith(f".{interface}"):
                return p.device
    return None


def port_for_interface(vid: int, pid: int, serial: Optional[str],
                       interface: int) -> Optional[str]:
    """The COM port of ``interface`` on the board with this USB serial, or None
    if it cannot be told (no serial, unknown platform, or the port is absent)."""
    if not serial:
        return None
    if sys.platform == "win32":
        return _windows_port(vid, pid, serial, interface)
    return _location_port(vid, pid, serial, interface)


def pwrsup_port(serial: Optional[str]) -> Optional[str]:
    """The PwrSup COM port of the board with this USB serial."""
    return port_for_interface(CANLINX_VID, CANLINX_PID, serial, INTERFACE_PWRSUP)
