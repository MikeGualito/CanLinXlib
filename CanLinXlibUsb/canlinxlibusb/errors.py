"""
errors.py - exceptions raised by canlinxlibusb.

>>> CanLinX (not generated by CubeMX2) <<<

CanLinXlibCan and CanLinXlibLin catch these and re-raise their own types, so an
application only ever sees the exceptions of the library it called.
"""

from __future__ import annotations


class UsbError(Exception):
    """Base class for everything this package raises."""


class UsbDeviceNotFound(UsbError):
    """No CanLinX device on the bus, or none with the requested serial."""


class UsbBackendMissing(UsbError):
    """pyusb has no libusb backend.

    On Windows pyusb ships no DLL of its own; the libusb-package wheel has one.
    """


class UsbDeviceBusy(UsbError):
    """The vendor interface could not be claimed: another PROCESS owns it.

    libusb on Windows gives exactly ONE handle to a WinUSB interface. Inside one
    process both libraries share it, so this means a different process (another
    script, a python-can bus, a test suite left running) holds the device.
    """
