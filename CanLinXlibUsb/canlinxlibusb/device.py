"""
device.py - one libusb handle per CanLinX board, shared by CAN and LIN.

>>> CanLinX (not generated by CubeMX2) <<<

CAN (gs_usb) and LIN travel over the SAME WinUSB interface of the board
(interface 2), on two independent bulk pairs. libusb on Windows gives only one
handle to a WinUSB interface, so the two libraries cannot each open their own:
whichever came second would fail. They both call SharedDevice.acquire() instead,
which opens and claims the interface on the first call and hands the same handle
to the rest of the process, and gives it back when the last user releases it.

Two PROCESSES still cannot share a board; that is a limit of libusb on Windows,
and it is reported as UsbDeviceBusy.
"""

from __future__ import annotations

import threading
from typing import Optional

import usb.core
import usb.util

from .errors import UsbBackendMissing, UsbDeviceBusy, UsbDeviceNotFound

# --- USB identity and endpoints of the vendor interface ----------------------
CANLINX_VID = 0x0483
CANLINX_PID = 0x5710
VENDOR_INTERFACE = 2

CAN_EP_IN = 0x83
CAN_EP_OUT = 0x02
LIN_EP_IN = 0x84
LIN_EP_OUT = 0x03

_REQ_OUT = usb.util.CTRL_OUT | usb.util.CTRL_TYPE_VENDOR | usb.util.CTRL_RECIPIENT_INTERFACE
_REQ_IN = usb.util.CTRL_IN | usb.util.CTRL_TYPE_VENDOR | usb.util.CTRL_RECIPIENT_INTERFACE


def _backend():
    """A libusb backend, from libusb-package if pyusb has none of its own."""
    from usb.backend import libusb1
    be = libusb1.get_backend()
    if be is not None:
        return be
    try:
        import libusb_package
        be = libusb_package.get_libusb1_backend()
    except ImportError as exc:
        raise UsbBackendMissing(
            "pyusb found no libusb backend and libusb-package is not "
            "installed. Run: pip install libusb-package") from exc
    if be is None:
        raise UsbBackendMissing("libusb-package provided no usable backend")
    return be


def find_devices() -> list:
    """Every CanLinX device currently attached."""
    return list(usb.core.find(find_all=True, idVendor=CANLINX_VID,
                              idProduct=CANLINX_PID, backend=_backend()))


def serial_of(dev) -> str:
    """The device's USB serial, or "" when it cannot be read right now."""
    try:
        return dev.serial_number or ""
    except (usb.core.USBError, NotImplementedError, ValueError):
        return ""


def list_serials() -> list:
    """The USB serial number of every CanLinX board attached.

    Each board derives its serial from the MCU's unique device ID, which is the
    only thing that tells two of them apart: VID/PID are identical and the
    enumeration order is not stable.
    """
    return [serial_of(dev) for dev in find_devices()]


def _key(dev):
    """Identity of a physical device, stable across usb.core.find() calls."""
    bus = getattr(dev, "bus", None)
    address = getattr(dev, "address", None)
    if bus is None or address is None:
        return id(dev)
    return (bus, address)


class SharedDevice:
    """A claimed CanLinX vendor interface, shared inside this process.

    Get one with :meth:`acquire` and give it back with :meth:`release`; do not
    construct it directly.
    """

    _registry: dict = {}
    _registry_lock = threading.Lock()

    def __init__(self, dev, key, serial: str = "") -> None:
        self.dev = dev
        self._key = key
        self._serial = serial
        self._users = 0
        self._ctrl_lock = threading.Lock()

    # --- acquire / release --------------------------------------------------

    @classmethod
    def acquire(cls, serial: Optional[str] = None) -> "SharedDevice":
        """Open the board (or reuse the handle this process already has).

        :param serial: USB serial of the board to open. None takes the first one
            found. With two boards attached, pass it: it is the only thing that
            tells them apart.
        :raises UsbDeviceNotFound: nothing attached, or no board with that serial.
        :raises UsbDeviceBusy: another process holds the interface.
        """
        with cls._registry_lock:
            devices = find_devices()
            if not devices:
                raise UsbDeviceNotFound(
                    f"no CanLinX device ({CANLINX_VID:04x}:{CANLINX_PID:04x}). "
                    "Is it plugged in, and did WinUSB bind to interface "
                    f"{VENDOR_INTERFACE}?")
            if serial is not None:
                # Reading the serial is a live control transfer, and it throws
                # for a device whose vendor interface Windows has not finished
                # binding to WinUSB -- which happens for seconds after a board
                # with a new serial is first plugged in. Skip such a device
                # instead of letting the exception escape: a board that cannot
                # be identified is not the one that was asked for, and crashing
                # here would hide the boards that ARE ready.
                # A board this process already holds cannot be asked for its
                # serial again (the string request fails while the interface
                # is claimed), so the one remembered at open time is used.
                attached = []
                for d in devices:
                    held = cls._registry.get(_key(d))
                    attached.append((d, held._serial if held else serial_of(d)))
                devices = [d for d, s in attached if s == serial]
                if not devices:
                    seen = ", ".join(repr(s) if s else "<unreadable>"
                                     for _, s in attached) or "none"
                    raise UsbDeviceNotFound(
                        f"no CanLinX with serial {serial!r}; attached: {seen}. "
                        "An <unreadable> entry usually means Windows is still "
                        "binding that device to WinUSB -- retry in a few "
                        "seconds.")
            dev = devices[0]
            key = _key(dev)

            shared = cls._registry.get(key)
            if shared is not None:
                shared._users += 1
                return shared

            board_serial = serial if serial is not None else serial_of(dev)
            try:
                usb.util.claim_interface(dev, VENDOR_INTERFACE)
            except usb.core.USBError as exc:
                raise UsbDeviceBusy(
                    "could not claim the vendor interface. libusb on Windows "
                    "gives only ONE handle to it: close any other process "
                    "using the CAN or LIN channel (another script, a "
                    "python-can bus, a test suite or a --burst left running). "
                    f"Original error: {exc}") from exc

            shared = cls(dev, key, board_serial)
            shared._users = 1
            cls._registry[key] = shared
            return shared

    def release(self) -> None:
        """Give the handle back; the interface is released with the last user."""
        cls = type(self)
        with cls._registry_lock:
            if self._users <= 0:
                return
            self._users -= 1
            if self._users > 0:
                return
            cls._registry.pop(self._key, None)
        try:
            usb.util.release_interface(self.dev, VENDOR_INTERFACE)
        except Exception:
            pass
        try:
            usb.util.dispose_resources(self.dev)
        except Exception:
            pass

    @property
    def serial_number(self) -> str:
        """USB serial of the board, read before the interface was claimed."""
        return self._serial

    # --- transfers ------------------------------------------------------------

    def ctrl_out(self, request: int, payload: bytes = b"", value: int = 0,
                 timeout_ms: int = 1000) -> None:
        """Vendor control OUT request addressed to the vendor interface."""
        with self._ctrl_lock:
            self.dev.ctrl_transfer(_REQ_OUT, request, value, VENDOR_INTERFACE,
                                   payload, timeout_ms)

    def ctrl_in(self, request: int, length: int, value: int = 0,
                timeout_ms: int = 1000) -> bytes:
        """Vendor control IN request addressed to the vendor interface."""
        with self._ctrl_lock:
            return bytes(self.dev.ctrl_transfer(_REQ_IN, request, value,
                                                VENDOR_INTERFACE, length,
                                                timeout_ms))

    def read(self, endpoint: int, size: int, timeout_ms: int):
        """Bulk read. ``size`` must be a multiple of 64 (WinUSB rejects others)."""
        return self.dev.read(endpoint, size, timeout_ms)

    def write(self, endpoint: int, data: bytes, timeout_ms: int):
        """Bulk write."""
        return self.dev.write(endpoint, data, timeout_ms)
